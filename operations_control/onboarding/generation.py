def _originates(p: PortfolioStanding) -> bool:
    """The governed default: direct books originate, acquired books do not —
    unless onboarding was told otherwise (portfolio_registry.example.yaml)."""
    if p.originates is not None:
        return bool(p.originates)
    return p.portfolio_type == "direct"


def render_portfolio_registry(profile: ClientOnboardingProfile,
                              *, base: Optional[Dict[str, Any]] = None
                              ) -> Tuple[Dict[str, Any], List[str]]:
    """Per-portfolio business metadata, in the per-client shape the resolver
    already supports (``clients: {<id>: {portfolios: [...]}}``)."""
    doc = copy.deepcopy(base) if base else {}
    clients = doc.setdefault("clients", {})
    block = clients.setdefault(profile.client_id, {})
    entries: List[Dict[str, Any]] = []
    existing = {str(e.get("source_portfolio_id")): e
                for e in (block.get("portfolios") or [])
                if isinstance(e, dict)}
    for p in profile.portfolios:
        entry = dict(existing.get(p.portfolio_id) or {})
        entry.update({
            "source_portfolio_id": p.portfolio_id,
            "source_portfolio_type": p.portfolio_type,
            "source_portfolio_label": p.display_name,
            "originates": _originates(p),
            "pipeline_data_available": p.has_pipeline,
        })
        # forecast_treatment is only set where onboarding actually knows: a
        # supplied runoff curve is a governed input Trakt consumes, never one
        # it generates, so an acquired book without one is left to the
        # platform's hold-constant default rather than given a treatment here.
        if _originates(p):
            entry["forecast_treatment"] = "origination"
        elif entry.get("runoff_curve"):
            entry["forecast_treatment"] = "runoff"
        entries.append(entry)
    block["portfolios"] = entries
    return doc, [f"{len(entries)} portfolio"
                 f"{'s' if len(entries) != 1 else ''} described."]


