def render_source_records(profile: ClientOnboardingProfile,
                          *, registry: Optional[SourceRegistry] = None
                          ) -> Tuple[List[SourceRecord], List[str]]:
    """The source registry records a profile implies.

    An EXISTING record is preserved and only extended: its approved mapping,
    pinned schema fingerprint, role schemas and last-successful markers are
    never cleared by onboarding — those are earned by a real delivery, and
    resetting them would send a recognised recurring pack back through source
    onboarding. Onboarding owns the business facts (source system, cadence,
    regime scope); the registry owns the delivery evidence.
    """
    out: List[SourceRecord] = []
    notes: List[str] = []
    for s in profile.sources:
        portfolio = profile.portfolio(s.portfolio_id)
        existing = (registry.lookup(profile.client_id, s.portfolio_id,
                                    s.dataset, s.frequency)
                    if registry is not None else None)
        record = SourceRecord(
            client_id=profile.client_id,
            source_portfolio_id=s.portfolio_id,
            dataset=s.dataset,
            frequency=s.frequency,
            source_portfolio_type=(portfolio.portfolio_type
                                   if portfolio else None),
            source_system=s.source_system or (portfolio.source_system
                                              if portfolio else "") or None,
            regime_required=bool(s.regime_required),
            expected_columns=list(s.expected_files),
            status=s.status,
        )
        if existing is not None:
            record.approved_mapping_id = existing.approved_mapping_id
            record.mapping_config_path = existing.mapping_config_path
            record.mapping_version = existing.mapping_version
            record.expected_schema_fingerprint = existing.expected_schema_fingerprint
            record.file_role_schemas = dict(existing.file_role_schemas)
            record.file_role_aliases = dict(existing.file_role_aliases)
            record.last_successful_run_id = existing.last_successful_run_id
            record.last_successful_reporting_period = \
                existing.last_successful_reporting_period
            record.expected_columns = (list(s.expected_files)
                                       or list(existing.expected_columns))
            # A source already proven by a delivery stays active; onboarding
            # never demotes it back to pending review.
            if existing.status == STATUS_ACTIVE and existing.has_approved_mapping:
                record.status = STATUS_ACTIVE
            notes.append(f"{record.key} updated (approved mapping preserved).")
        else:
            notes.append(f"{record.key} registered, awaiting its first pack.")
        out.append(record)
    return out, notes


# --------------------------------------------------------------------------- #
# Plan / apply
# --------------------------------------------------------------------------- #

def plan(profile: ClientOnboardingProfile, *, store, registry=None,
         spec: Optional[Dict[str, Any]] = None,
         base_documents: Optional[Dict[str, Dict[str, Any]]] = None
         ) -> List[Artefact]:
    """Everything approval would write, with the current content alongside.

    Nothing is written. ``store`` is an :class:`~.store.OnboardingStore`.

    ``base_documents`` carries the legacy documents a MIGRATED client is being
    adopted from (``{kind: parsed yaml}``), so blocks onboarding does not own —
    enrichment, transformations, persistence, deal-structure triggers — survive
    adoption intact. A genuinely new client supplies none, and starts clean:
    inheriting another client's enrichment rules would be exactly the silent
    coupling this capability exists to remove.
    """
    spec = spec or standing_field_spec()
    base_documents = base_documents or {}
    client_id = profile.client_id
    artefacts: List[Artefact] = []

    # -- client configuration ---------------------------------------------- #
    rel = client_config_rel(client_id)
    previous = store.read_artefact(client_id, rel)
    base = (_parse(previous) if previous
            else copy.deepcopy(base_documents.get(ARTEFACT_CLIENT_CONFIG) or {}))
    doc, notes = render_client_config(profile, base=base, spec=spec)
    text = _dump(doc)
    artefacts.append(Artefact(
        kind=ARTEFACT_CLIENT_CONFIG, rel=rel, label="Client configuration",
        action=_action(previous, text), text=text,
        previous_text=previous or "", summary=notes))

    # -- investor reporting overlay ---------------------------------------- #
    if "investor_reporting" in profile.reporting.products:
        rel12 = annex12_config_rel(client_id)
        previous12 = store.read_artefact(client_id, rel12)
        base12 = (_parse(previous12) if previous12
                  else copy.deepcopy(
                      base_documents.get(ARTEFACT_ANNEX12_CONFIG) or {}))
        doc12, notes12 = render_annex12_config(profile, base=base12, spec=spec)
        text12 = _dump(doc12)
        artefacts.append(Artefact(
            kind=ARTEFACT_ANNEX12_CONFIG, rel=rel12,
            label="Investor report configuration",
            action=_action(previous12, text12), text=text12,
            previous_text=previous12 or "", summary=notes12))

    # -- portfolio registry ------------------------------------------------- #
    relp = portfolio_registry_rel(client_id)
    previousp = store.read_artefact(client_id, relp)
    docp, notesp = render_portfolio_registry(profile, base=_parse(previousp))
    textp = _dump(docp)
    artefacts.append(Artefact(
        kind=ARTEFACT_PORTFOLIO_REGISTRY, rel=relp, label="Portfolio metadata",
        action=_action(previousp, textp), text=textp,
        previous_text=previousp or "", summary=notesp))

    # -- source registry ---------------------------------------------------- #
    records, notesr = render_source_records(profile, registry=registry)
    rows: List[Dict[str, Any]] = []
    for record in records:
        existing = (registry.lookup(client_id, record.source_portfolio_id,
                                    record.dataset, record.frequency)
                    if registry is not None else None)
        portfolio = profile.portfolio(record.source_portfolio_id)
        rows.append({
            **record.to_dict(),
            "action": "update" if existing is not None else "create",
            "expected_location": blob_prefix(
                client_id, record.source_portfolio_type or "direct",
                record.dataset, record.frequency, record.source_portfolio_id),
            "portfolio_label": (portfolio.display_name if portfolio else ""),
        })
    artefacts.append(Artefact(
        kind=ARTEFACT_SOURCE_REGISTRY, rel="source registry",
        label="Source registrations",
        action=("update" if any(r["action"] == "update" for r in rows)
                else ("create" if rows else "unchanged")),
        records=rows, summary=notesr))
    return artefacts


def _action(previous: Optional[str], text: str) -> str:
    if previous is None:
        return "create"
    return "unchanged" if previous == text else "update"


def apply(profile: ClientOnboardingProfile, *, store, version: int,
          registry=None, artefacts: Optional[List[Artefact]] = None,
          base_documents: Optional[Dict[str, Dict[str, Any]]] = None
          ) -> List[Dict[str, Any]]:
    """Write the planned artefacts. Called only after operator approval."""
    artefacts = artefacts or plan(profile, store=store, registry=registry,
                                  base_documents=base_documents)
    written: List[Dict[str, Any]] = []
    for artefact in artefacts:
        if artefact.kind == ARTEFACT_SOURCE_REGISTRY:
            if registry is not None:
                records, _ = render_source_records(profile, registry=registry)
                for record in records:
                    registry.upsert(record)
            written.append({"kind": artefact.kind, "target": "source registry",
                            "action": artefact.action,
                            "detail": {"records": [r.get("client_id", "")
                                                   and f"{r['client_id']}/"
                                                   f"{r['source_portfolio_id']}/"
                                                   f"{r['dataset']}/"
                                                   f"{r['frequency']}"
                                                   for r in artefact.records]}})
            continue
        if artefact.action == "unchanged":
            written.append({"kind": artefact.kind, "target": artefact.rel,
                            "action": "unchanged", "detail": {}})
            continue
        uri = store.write_artefact(profile.client_id, version, artefact.rel,
                                   artefact.text)
        written.append({"kind": artefact.kind, "target": artefact.rel,
                        "action": artefact.action, "detail": {"uri": uri}})
    return written
