"""operations_control.onboarding.generation — profile -> governed artefacts.

The operator answers business questions; this module writes the technical
configuration. It generates the artefacts Trakt ALREADY reads, in their existing
formats:

  ``config/client/config_client_{CLIENT}.yaml``  the master client configuration
                                                 (engine/orchestrator/trakt_run.py
                                                 ``--master-config``,
                                                 operations_control.configuration.
                                                 resolver, annex2.preflight)
  ``config/client/config_client_annex12.yaml``   the investor-report overlay
                                                 (engine/gate_4_projection/
                                                 annex12_projector.py ``--config``)
  ``config/client/portfolio_registry.yaml``      per-portfolio business metadata
                                                 (mi_agent/portfolio_metadata.py)
  the durable source registry                    one record per client/portfolio/
                                                 dataset/frequency
                                                 (apps.blob_trigger_app.source_registry)

Generation is a MERGE, never a replacement. Blocks the wizard does not own —
``transformations``, ``enrichment``, ``pipeline_persistence``, ``loan_engine``,
anything an administrator has added — are carried through from the current
document untouched. A plan is produced first (:func:`plan`), shown to the
operator, and only written on approval (:func:`apply`).
"""

