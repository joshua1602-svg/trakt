def render_client_config(profile: ClientOnboardingProfile,
                         *, base: Optional[Dict[str, Any]] = None,
                         spec: Optional[Dict[str, Any]] = None
                         ) -> Tuple[Dict[str, Any], List[str]]:
    """The master client configuration, in its existing shape.

    Only the blocks onboarding owns are written; everything else in ``base``
    survives. Returns the document and a plain-English change summary.
    """
    spec = spec or standing_field_spec()
    doc = copy.deepcopy(base) if base else {}
    notes: List[str] = []
    c = profile.client

    # -- client identity (existing `client:` block) ------------------------- #
    client_block = doc.setdefault("client", {})
    client_block["client_id"] = c.client_id
    client_block["display_name"] = c.client_name
    client_block["environment"] = c.environment or "production"
    client_block["legal_entity_name"] = c.legal_entity_name
    client_block["time_zone"] = c.time_zone
    client_block["reporting_contact"] = {
        "name": c.primary_reporting_contact, "email": c.reporting_email}
    client_block["operational_contact"] = {
        "name": c.operational_contact, "email": c.operational_email}
    notes.append(f"Client identity for {c.client_name}.")

    # -- portfolio defaults (existing `portfolio:` block) ------------------- #
    # The legacy block is single-valued: it describes the client's dominant
    # book. Multi-portfolio detail lives in the portfolio registry, so this
    # block is populated from the first portfolio and stays compatible with
    # every existing reader.
    portfolio_block = doc.setdefault("portfolio", {})
    if profile.portfolios:
        first = profile.portfolios[0]
        portfolio_block["asset_class"] = first.asset_class
    portfolio_block["country"] = (c.jurisdiction or "").upper()
    portfolio_block["base_currency"] = (c.reporting_currency or "").upper()
    notes.append("Portfolio jurisdiction and reporting currency.")

    # -- regimes (existing default_regime / supported_regimes / regime) ----- #
    supported: List[str] = []
    for p in profile.portfolios:
        for regime in (ASSET_MODEL.get(p.asset_class, {})
                       .get("supports_regimes") or []):
            if regime not in supported:
                supported.append(regime)
    if "investor_reporting" in profile.reporting.products:
        annex12 = (spec.get("products", {}).get("investor_reporting", {})
                   .get("regime_id") or "ESMA_Annex12")
        if annex12 not in supported:
            supported.append(annex12)
    if supported:
        doc["supported_regimes"] = supported
        chosen = ("ESMA_Annex2"
                  if "esma_annex2" in profile.reporting.products
                  and "ESMA_Annex2" in supported else supported[0])
        doc["default_regime"] = chosen
        # Retained for backward compatibility, exactly as the legacy file does.
        doc["regime"] = chosen
        notes.append("Regime capability set: " + ", ".join(supported) + ".")

    # -- pipeline switches (existing `pipeline:` block) --------------------- #
    pipeline = doc.setdefault("pipeline", {})
    pipeline.setdefault("loan_engine_enabled", False)
    pipeline["mi_enabled"] = True
    pipeline["esma_enabled"] = "esma_annex2" in profile.reporting.products
    notes.append("Reporting products: "
                 + (", ".join(sorted(profile.reporting.products)) or "MI only")
                 + ".")

    # -- regime answers routed by the governed spec ------------------------- #
    for product_key, answers in (profile.regime or {}).items():
        product = (spec.get("products") or {}).get(product_key) or {}
        for f in product.get("fields") or []:
            target = str(f.get("writes_to") or "")
            if not target.startswith(f"{ARTEFACT_CLIENT_CONFIG}:"):
                continue
            value = answers.get(f.get("key"))
            if value is None or not str(value).strip():
                continue
            dotted = target.split(":", 1)[1]
            if f.get("format") == "boolean":
                value = _yes(value)
            elif f.get("format") == "country":
                value = str(value).strip().upper()
            elif f.get("format") == "lei":
                value = str(value).strip().upper()
            else:
                value = str(value).strip()
            _deep_set(doc, dotted, value)
    if profile.regime.get("esma_annex2"):
        notes.append("Annex 2 standing values injected into every reported row.")

    # The UK geography override carries a governed shape, not just a flag: when
    # switched on it must name the value and the fields it applies to, exactly
    # as the legacy configuration does.
    if _deep_get(doc, "regime_overrides.ESMA_Annex2.uk_geography.enabled"):
        _deep_set(doc, "regime_overrides.ESMA_Annex2.uk_geography.override_value",
                  "GBZZZ")
        _deep_set(doc,
                  "regime_overrides.ESMA_Annex2.uk_geography.target_fields",
                  ["geographic_region_obligor", "geographic_region_collateral"])

    # -- static reporting: branding + conventions --------------------------- #
    sr = profile.static_reporting
    if sr.app_title or sr.primary_color or sr.logo_uri or sr.disclaimer:
        mi = doc.setdefault("mi", {})
        branding = mi.setdefault("branding", {})
        if sr.app_title:
            branding["app_title"] = sr.app_title
        if sr.primary_color:
            branding.setdefault("theme", {})["primary_color"] = sr.primary_color
        if sr.logo_uri:
            branding["logo_uri"] = sr.logo_uri
        if sr.disclaimer:
            branding["disclaimer"] = sr.disclaimer
        notes.append("Report branding.")
    if sr.day_count_convention or sr.payment_convention:
        engine = doc.setdefault("loan_engine", {})
        if sr.day_count_convention:
            engine["day_count_convention"] = sr.day_count_convention
        if sr.payment_convention:
            engine["interest_payment_frequency"] = sr.payment_convention
        notes.append("Calculation conventions.")

    # -- reporting parties (no regime home; kept with the client) ----------- #
    parties = {k: v for k, v in (
        ("investor_contact", sr.investor_contact),
        ("investor_email", sr.investor_email),
        ("trustee_name", sr.trustee_name),
        ("warehouse_lender", sr.warehouse_lender),
        ("reporting_convention", sr.reporting_convention),
    ) if str(v or "").strip()}
    if parties:
        doc["reporting_parties"] = parties
        notes.append("Standing reporting parties (trustee, investor contact, "
                     "warehouse lender).")
    return doc, notes


# --------------------------------------------------------------------------- #
# Investor reporting overlay
# --------------------------------------------------------------------------- #

def render_annex12_config(profile: ClientOnboardingProfile,
                          *, base: Optional[Dict[str, Any]] = None,
                          spec: Optional[Dict[str, Any]] = None
                          ) -> Tuple[Dict[str, Any], List[str]]:
    """The Annex 12 client instance overlay.

    The projector deep-merges template -> asset overlay -> this document, and
    resolves IVSS1/IVSS3/IVSS4 from the master configuration when they are
    absent. Deal-structure blocks already present (triggers, cashflows) are
    carried through untouched — they are not standing client information.
    """
    spec = spec or standing_field_spec()
    doc = copy.deepcopy(base) if base else {}
    notes: List[str] = []
    annex12 = doc.setdefault("annex12", {})
    meta = annex12.setdefault("meta", {})
    meta.setdefault("template", "ESMA Annex 12 (Investor Report)")
    annex12.setdefault("assumptions", {})["reporting_currency"] = (
        profile.client.reporting_currency or "").upper()

    product = (spec.get("products") or {}).get("investor_reporting") or {}
    written = 0
    for f in product.get("fields") or []:
        target = str(f.get("writes_to") or "")
        if not target.startswith(f"{ARTEFACT_ANNEX12_CONFIG}:"):
            continue
        value = (profile.regime.get("investor_reporting") or {}).get(f.get("key"))
        if value is None or not str(value).strip():
            continue
        _deep_set(doc, target.split(":", 1)[1], str(value).strip())
        written += 1
    if written:
        notes.append(f"{written} standing investor-report field"
                     f"{'s' if written != 1 else ''}.")
    if profile.client.legal_entity_name:
        deal = annex12.setdefault("deal", {})
        deal.setdefault("IVSS3", profile.client.legal_entity_name)
        deal.setdefault("IVSS4", profile.client.legal_entity_name)
    return doc, notes


